/**
 * 유저 메시지 빌더 — 운세 결과 + 사용자 컨텍스트 + 이전 이력 + 현재 질문
 */
export const buildFollowUpUserPrompt = (params: {
  fortuneType: FollowUpFortuneType;
  fortuneResult: unknown;
  userContext: {
    currentAge: number;
    birthDate: string;
    todayDate: string;
  };
  history: { question: string; answer: string }[];
  question: string;
}): string => {
  const { fortuneType, fortuneResult, userContext, history, question } = params;
  const fortuneLabel = FORTUNE_TYPE_LABELS[fortuneType];

  const resultJson = JSON.stringify(fortuneResult, null, 2);

  const historyBlock =
    history.length === 0
      ? "(아직 이전 대화 없음)"
      : history
          .map(
            (h, i) =>
              `[${i + 1}] 질문: ${h.question}\n[${i + 1}] 답변: ${h.answer}`
          )
          .join("\n\n");

  return `## 사용자 컨텍스트
- 오늘 날짜: ${userContext.todayDate}
- 사용자 생년월일: ${userContext.birthDate}
- 사용자 현재 나이: **만 ${userContext.currentAge}세**
- 중요: 시간·나이 관련 답변은 반드시 **만 ${userContext.currentAge}세 이후의 미래 시점**만 말해야 합니다. 과거나 현재 이하는 절대 언급 금지.

## 사용자의 ${fortuneLabel} 결과
\`\`\`json
${resultJson}
\`\`\`

## 이전 대화 이력
${historyBlock}

## 사용자의 이번 질문
${question}

위 운세 결과와 사용자 컨텍스트를 바탕으로, 7가지 품질 규칙을 모두 지켜 답변하세요.
특히 첫 문장은 meta-commentary 없이 바로 결론이어야 합니다.
반드시 차트 요소(궁·주성·사화·대운)를 최소 1회 이상 인용하고, 질문 범위 밖 내용은 절대 넣지 마세요.`;
};
