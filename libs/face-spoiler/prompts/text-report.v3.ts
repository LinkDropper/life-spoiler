/** 프롬프트용 패턴 할당 테이블 문자열. */
const buildOneLinerPatternTable = (regionScores: RegionRawScore[]): string =>
  regionScores
    .map((r, i) => {
      const pattern = REGION_ONE_LINER_PATTERNS[r.region];
      return `${i + 1}. ${r.label} → **${pattern.name}** — ${pattern.hint}`;
    })
    .join("\n");

